"""Generate frontend TypeScript types from the FastAPI OpenAPI schema.

Usage:
    python -m sohbench.api.typegen           # (re)write frontend/app/types/*
    python -m sohbench.api.typegen --check   # exit 1 if the files are stale

Outputs (checked into the repo, consumed by the no-build frontend via JSDoc
``@typedef {import("./types/api").X}`` annotations):

- ``frontend/app/types/openapi.json`` — the full OpenAPI document
- ``frontend/app/types/api.d.ts``     — interfaces for every schema component
  plus an ``ApiOperations`` map of ``"METHOD /path"`` -> request/query/response
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HEADER = (
    "// Generated by `python -m sohbench.api.typegen` — do not edit by hand.\n"
    "// Contract source: src/sohbench/api/schemas.py (served at /openapi.json).\n"
)

_IDENTIFIER = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def repo_root() -> Path:
    return Path(__file__).resolve().parents[3]


def default_out_dir() -> Path:
    return repo_root() / "frontend" / "app" / "types"


def build_openapi() -> dict:
    from .app import create_app

    return create_app(None).openapi()


def _prop_name(name: str) -> str:
    return name if _IDENTIFIER.match(name) else json.dumps(name)


def _parenthesize(rendered: str) -> str:
    return f"({rendered})" if "|" in rendered or "&" in rendered else rendered


def ts_type(schema) -> str:
    if not isinstance(schema, dict) or not schema:
        return "unknown"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    if "anyOf" in schema or "oneOf" in schema:
        variants = schema.get("anyOf") or schema.get("oneOf")
        rendered = []
        for variant in variants:
            item = ts_type(variant)
            if item not in rendered:
                rendered.append(item)
        return " | ".join(rendered) or "unknown"
    if "allOf" in schema:
        rendered = [ts_type(part) for part in schema["allOf"]]
        return " & ".join(rendered) or "unknown"
    schema_type = schema.get("type")
    if isinstance(schema_type, list):
        return " | ".join(ts_type({**schema, "type": item}) for item in schema_type)
    if schema_type == "array":
        return f"{_parenthesize(ts_type(schema.get('items')))}[]"
    if schema_type == "object" or ("properties" in schema and schema_type is None):
        properties = schema.get("properties")
        if properties:
            required = set(schema.get("required") or [])
            fields = "; ".join(
                f"{_prop_name(name)}{'' if name in required else '?'}: {ts_type(prop)}"
                for name, prop in properties.items()
            )
            return "{ " + fields + " }"
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            return f"Record<string, {ts_type(additional)}>"
        return "Record<string, unknown>"
    scalar = {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }
    return scalar.get(schema_type, "unknown")


def _emit_interface(name: str, schema: dict) -> str:
    properties = schema.get("properties") or {}
    if not properties:
        return f"export type {name} = Record<string, unknown>;\n"
    required = set(schema.get("required") or [])
    lines = [f"export interface {name} {{"]
    for prop, prop_schema in properties.items():
        optional = "" if prop in required else "?"
        lines.append(f"  {_prop_name(prop)}{optional}: {ts_type(prop_schema)};")
    if schema.get("additionalProperties", False) is not False:
        lines.append("  [key: string]: unknown;")
    lines.append("}\n")
    return "\n".join(lines)


def _success_response_type(operation: dict) -> str:
    responses = operation.get("responses") or {}
    for status in sorted(responses):
        if not status.startswith("2"):
            continue
        content = (responses[status].get("content") or {}).get("application/json") or {}
        if "schema" in content:
            return ts_type(content["schema"])
    return "unknown"


def _emit_operations(openapi: dict) -> str:
    lines = [
        "/** Request/response contract for every endpoint, keyed by `METHOD /path`. */",
        "export interface ApiOperations {",
    ]
    for path, path_item in (openapi.get("paths") or {}).items():
        for method in ("get", "post", "put", "patch", "delete"):
            operation = path_item.get(method)
            if not operation:
                continue
            entries = []
            query_params = [
                param
                for param in operation.get("parameters") or []
                if param.get("in") == "query"
            ]
            if query_params:
                fields = "; ".join(
                    f"{_prop_name(param['name'])}"
                    f"{'' if param.get('required') else '?'}: {ts_type(param.get('schema'))}"
                    for param in query_params
                )
                entries.append(f"query?: {{ {fields} }}")
            body = (
                ((operation.get("requestBody") or {}).get("content") or {})
                .get("application/json", {})
                .get("schema")
            )
            if body:
                entries.append(f"request?: {ts_type(body)}")
            entries.append(f"response: {_success_response_type(operation)}")
            key = json.dumps(f"{method.upper()} {path}")
            lines.append(f"  {key}: {{ {'; '.join(entries)} }};")
    lines.append("}\n")
    return "\n".join(lines)


def render_dts(openapi: dict) -> str:
    parts = [HEADER]
    schemas = (openapi.get("components") or {}).get("schemas") or {}
    for name in sorted(schemas):
        parts.append(_emit_interface(name, schemas[name]))
    parts.append(_emit_operations(openapi))
    return "\n".join(parts)


def render_openapi_json(openapi: dict) -> str:
    return json.dumps(openapi, ensure_ascii=False, indent=2) + "\n"


def generate(out_dir: Path | None = None) -> dict[Path, str]:
    out = out_dir or default_out_dir()
    openapi = build_openapi()
    return {
        out / "openapi.json": render_openapi_json(openapi),
        out / "api.d.ts": render_dts(openapi),
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser("sohbench-api-typegen")
    parser.add_argument("--check", action="store_true", help="verify files are up to date")
    parser.add_argument("--out-dir", default=None)
    args = parser.parse_args(argv)

    out_dir = Path(args.out_dir) if args.out_dir else default_out_dir()
    rendered = generate(out_dir)
    if args.check:
        stale = [
            str(path)
            for path, content in rendered.items()
            if not path.exists() or path.read_text(encoding="utf-8") != content
        ]
        if stale:
            print("stale generated types (run `python -m sohbench.api.typegen`):")
            for path in stale:
                print(f"  {path}")
            return 1
        print("generated types are up to date")
        return 0
    out_dir.mkdir(parents=True, exist_ok=True)
    for path, content in rendered.items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
